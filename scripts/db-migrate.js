// scripts/db-migrate.js
// Executes all pending migration files (those not yet recorded in
// schema_migrations) in filename order, then regenerates config/db/schema.sql
// so it always reflects the current state of the database.
// Usage: npm run db:migrate

require('dotenv').config();
const fs = require('fs');
const path = require('path');
const db = require('../config/db');
const { executeFile } = require('./run-sql');

const MIGRATIONS_DIR = path.join(__dirname, '..', 'config', 'db', 'migrations');
const SCHEMA_PATH = path.join(__dirname, '..', 'config', 'db', 'schema.sql');
const DB_NAME = process.env.DB_NAME || 'vu_quiz_questions_data';

async function main() {
    // Ensure the migrations tracking table exists.
    await db.query(`
        CREATE TABLE IF NOT EXISTS schema_migrations (
            id INT UNSIGNED NOT NULL AUTO_INCREMENT,
            version VARCHAR(255) NOT NULL,
            name VARCHAR(255) NOT NULL,
            applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (id),
            UNIQUE KEY uq_schema_migrations_version (version)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
    `);

    // Load already-applied migration versions.
    const [appliedRows] = await db.query('SELECT version FROM schema_migrations');
    const applied = new Set(appliedRows.map((r) => r.version));

    // List migration files sorted by name (numeric prefix gives ordering).
    const files = fs.readdirSync(MIGRATIONS_DIR)
        .filter((f) => f.endsWith('.sql'))
        .sort();

    const pending = files.filter((f) => !applied.has(f));

    if (pending.length === 0) {
        console.log('✅ No pending migrations. Database is up to date.');
    } else {
        console.log(`📦 Found ${pending.length} pending migration(s). Applying…`);
        for (const file of pending) {
            const filePath = path.join(MIGRATIONS_DIR, file);
            const displayName = file
                .replace(/^\d+_/, '')
                .replace(/\.sql$/, '')
                .replace(/[_]/g, ' ');

            const statementCount = await executeFile(db, filePath);
            await db.query('INSERT INTO schema_migrations (version, name) VALUES (?, ?)', [
                file,
                displayName,
            ]);
            console.log(`   ✔ ${file} — ${statementCount} statement(s)`);
        }
        console.log(`✅ Applied ${pending.length} migration(s).`);
    }

    // Regenerate schema.sql so it reflects the current DB state (baseline + migrations).
    await regenerateSchema(db);

    console.log(`💡 Run "npm run db:seed" to load seed data for testing.`);
    process.exit(0);
}

// Dump the full schema from the live database into config/db/schema.sql.
async function regenerateSchema(targetDb) {
    const lines = [];
    lines.push('-- ============================================================================');
    lines.push('-- VU Empire Database Schema (Baseline + Migrations)');
    lines.push('-- ============================================================================');
    lines.push('-- Source-of-truth schema loaded by `npm run db:create` and regenerated by');
    lines.push('-- `npm run db:migrate` so it always reflects the DB state after migrations.');
    lines.push('-- Do not edit by hand; add a migration file in config/db/migrations/ instead.');
    lines.push('-- ============================================================================');
    lines.push('');
    lines.push(`CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;`);
    lines.push(`USE \`${DB_NAME}\`;`);
    lines.push('');

    // Migration tracking table definition.
    lines.push('-- Migration tracking table');
    lines.push(await getCreateTable(targetDb, 'schema_migrations'));
    lines.push('');

    // All other tables, in database order.
    const [tables] = await targetDb.query('SHOW TABLES');
    const tableKey = Object.keys(tables[0])[0];
    for (const row of tables) {
        const table = row[tableKey];
        if (table === 'schema_migrations') continue;
        lines.push(`-- Table: ${table}`);
        lines.push(await getCreateTable(targetDb, table));
        lines.push('');
    }

    fs.writeFileSync(SCHEMA_PATH, lines.join('\n').trimEnd() + '\n');
    console.log(`📄 Schema file updated: config/db/schema.sql`);
}

// Return the `SHOW CREATE TABLE` statement for a table/view (with trailing semicolon).
async function getCreateTable(targetDb, table) {
    const [rows] = await targetDb.query(`SHOW CREATE TABLE \`${table}\``);
    const createKey = Object.keys(rows[0]).find((k) => k.toLowerCase().includes('create'));
    if (!createKey) {
        throw new Error(`Could not read SHOW CREATE TABLE for \`${table}\``);
    }
    return rows[0][createKey].trim().endsWith(';')
        ? rows[0][createKey].trim()
        : rows[0][createKey].trim() + ';';
}

main().catch((err) => {
    console.error('❌ db:migrate failed:', err.message);
    process.exit(1);
});
